const dictionaries = { en, cs };
let current: 'en' | 'cs' = 'en';

export function setLanguage(language: Language, systemLocale: string) {
  current = language === 'auto' ? (systemLocale.toLowerCase().startsWith('cs') ? 'cs' : 'en') : language;
  document.documentElement.lang = current;
  for (const el of document.querySelectorAll<HTMLElement>('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n as MessageKey);
  }
  for (const el of document.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle as MessageKey);
  }
  for (const el of document.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder as MessageKey);
  }
}

export const currentLanguage = () => current;

export function t(key: MessageKey, vars: Record<string, string> = {}): string {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}
